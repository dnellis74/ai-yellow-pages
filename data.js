//   name: display name
//   category: General, Electronics, Apparel, Beauty, Home, Marketplace, Groceries, Platform, Pet supplies
//     (plus Pharmacy, Telecom, Sporting goods, Convenience, Auto, Jewelry, Office, Crafts, Alcohol, Fuel, and others added with the NRF merge; Airlines added 2026-10-25)
//   status: "checkout" | "announced" | "onboarding" | "browse" | "limited" | "blocked" | "unknown"
//     checkout   = a third-party agent can complete a purchase (verified live)
//     announced  = an agent integration has been announced but live checkout is not verified
//     onboarding = named as onboarding to an agent commerce suite, no live checkout yet
//     browse     = an agent can browse but not check out
//     limited    = partial support, manual setup, or case-by-case
//     blocked    = third-party agents are blocked
//     unknown    = no public policy found
//   channels: which agent surfaces/protocols the business works with
//   url: outbound link. Replace with your affiliate link when you have one.
//   evidence: short statement of the policy, with its date
//   source: URL backing the evidence
//   verified: date this entry was last checked (YYYY-MM-DD)
//   sales: annual sales/revenue in billions of US dollars (number), or null
//     where no figure is available. NRF entries use NRF Top 100 Retailers 2026
//     (Kantar) 2025 US retail sales; other figures use the period stated in
//     salesNote. Platforms get no figure by design (null, no salesNote).
//   salesNote: what the sales figure covers and where it came from; omitted
//     when there is no figure and nothing to explain (platforms).
// Sales figures are for sorting and scale context only; they are not a
// quality signal. Nulls sort last in the default size sort.
//   capability: what an agent can actually do, pure automation, no depth adjustment:
//     "A+" | "B+" | "B" | "C-" | "D" | "F" | "—"
//   capabilityNote: one line: what the agent can do
//   depth: depth of products offered, shoppable online:
//     "A+" | "A" | "B" | "C" | "D" | "F" | "—"
//   depthNote: one line: the assortment basis
//   overall: weighted rating, 60% capability + 40% depth (see formula below)
//     "A+" | "A" | "A-" | "B+" | "B" | "B-" | "C+" | "C" | "C-" | "D" | "F" | "—"
//   overallNote: one line: the blend and why
//   overallProvisional: true only for announced/onboarding entries (omit otherwise)
//   defunct: true only for businesses that have ceased operations (omit otherwise);
//     renders a Defunct badge on the card and a defunct notice on the detail page.
//
// CAPABILITY GRADE (pure automation; depth never adjusts it):
//   Verified full agent checkout (status checkout) -> A+.
//   Agent fills a cart or orders through a constrained channel, human or site
//     completes checkout (cart-only) -> B+.
//   Partial agent interaction with no verified cart or checkout: agent API/schema
//     (CVS), checkout existing only for some merchants/segments (all four
//     platforms: Wix, BigCommerce, Squarespace, WooCommerce) -> B.
//   Products viewable/discoverable only (status browse) -> C-.
//   No usable agent channel but not actively blocked: eligibility-gated sellers
//     (AAFES, Defense Commissary Agency, Amway) and networks with no single
//     national checkout (Health Mart, Good Neighbor Pharmacy, AVB BrandSource,
//     Piggly Wiggly, Save-A-Lot, Grocery Outlet) -> D.
//   Actively blocked for third-party agents (status blocked) -> F.
//   No policy found (status unknown) -> "—", except the six networks above,
//     which are D. Ungraded is not a failing grade: absence of evidence is
//     not a block.
//   Announced/onboarding: the grade the announced integration targets
//     (full checkout -> A+, cart assistant -> B+, discovery/first-party
//     assistant -> C-), with overallProvisional: true. Provisional targets:
//     A+: Ulta, JD Sports, Best Buy, Gap, Sephora, URBN, Ashley, Revolve,
//     Halara, Abercrombie; B+: Sprouts, Aldi; C-: Lowe's, Macy's, Apple.
//   Conversion from the previous single grade (verified, not blindly copied):
//     old verified A-band (A+, A, A-) were all checkout entries -> A+;
//     old B+ -> B+; old B -> B; old C- -> C-; old D -> D; old F -> F;
//     old "—" -> "—" (except the five unknown-status networks, which stay D).
//     Old provisional A -> A+ provisional; B+ -> B+ provisional;
//     C- -> C- provisional. The old A- entries (SKIMS, Gymshark, Everlane,
//     Monos) were checkout entries with low depth; depth no longer adjusts
//     capability, so they are now capability A+.
//
// DEPTH GRADE (depth of products offered, shoppable online):
//   A+: sales >= $50B, OR a marketplace with sales >= $10B, OR a marketplace
//     with clearly massive listing breadth even at lower revenue (Etsy: tens
//     of millions of listings -> A+, noted as such).
//   A: vertical specialist with sales >= $5B, OR generalist with sales >= $10B.
//     Generalist categories for this rule: General, Groceries, Discount,
//     Convenience, Airlines. All other categories count as specialist/vertical.
//   B: sales >= $1B with a real online catalog.
//   C: sales < $1B, OR a narrow single-brand catalog with undisclosed scale
//     (null-sales single brands -> C unless evidence shows a broader catalog).
//   D: minimal online catalog (locator/ads site, limited ordering).
//   F: no online catalog to shop (in-store only with no e-commerce, no
//     own-site online ordering, fuel-only).
//   "—": depth cannot be assessed from available evidence; used sparingly and
//     justified in the note (here: WinCo Foods only, where sources conflict
//     on whether online shopping exists).
//   Platforms: depth reflects merchant breadth: Shopify A+ (largest eligible
//     US merchant base), other platforms A.
//   Networks: depth from the network sales tier, with a note that it is
//     network-wide, not one storefront.
//   Depth is graded from sales, category, and evidence even for unknown-status
//     entries (depth is about the catalog, not agent policy). Example:
//     Walgreens has unknown agent status but $112.05B sales -> depth A+.
//   Sales-tier exceptions where evidence overrides the tier: Circle K is D
//     (US site mainly a locator, despite $11.58B network sales); Ross,
//     Market Basket, Exxon Mobil, and Murphy USA are F (no shoppable online
//     catalog, regardless of sales). Save-A-Lot and Grocery Outlet follow the
//     networks rule (sales-tier depth, network-wide note) even though their
//     central sites are locator/informational only.
//
// OVERALL RATING: weighted 60% capability, 40% depth.
//   Points: A+ 100, A 90, A- 80, B+ 70, B 60, B- 50, C+ 40, C 30, C- 20, D 10, F 0.
//   Score = round(0.6 x capability points + 0.4 x depth points).
//   Map: >=95 A+, 85-94 A, 75-84 A-, 65-74 B+, 55-64 B, 45-54 B-, 35-44 C+,
//     25-34 C, 15-24 C-, 5-14 D, <5 F.
//   If capability is "—", overall is "—" regardless of depth.
//   overallProvisional is true exactly when capability is provisional
//     (i.e. announced/onboarding entries only).
//
// UNGRADED RULE: "—" is not a failing grade. Capability "—" means no agent
// policy was found; depth "—" means depth cannot be assessed from available
// evidence; overall "—" follows capability "—" regardless of depth.
//

